/** Explicit model data for the remaining catalog. Bounds are checked snapshots, never measured at module load. */
interface CatalogEntry {
  asset: string;
  name: string;
  category: string;
  purpose: string;
  bounds: Bounds;
  pivot: 'base-center' | 'model-origin';
  placement: string;
  largest?: { node: NodeSample; bounds: Bounds };
  colorRole?: MaterialRole | readonly MaterialRole[];
  roles: readonly PaletteRoleUse[];
  fixed: string;
  variants?: readonly string[];
  anchors: readonly AnchorDescriptor[];
  slots: readonly string[];
  animation: 'none' | 'local';
  example: string;
  notes: string;
}

const STATES: readonly VisualState[] = ['normal', 'busy', 'warning', 'critical', 'inactive'];
const TRANSFORM = 'A new position interpolates while scene motion is on; paused, motion-off and reduced motion apply the target immediately. Routes and controllers own the root when present.';

function options(entry: CatalogEntry): OptionDescriptor[] {
  const asset = entry.asset, result: OptionDescriptor[] = [];
  if (entry.colorRole) result.push({ field: 'color', type: 'CSS #RRGGBB', default: 'unset (inherit scene/definition role)', update: 'rebuild', description: `Compatibility color for ${typeof entry.colorRole === 'string' ? entry.colorRole : entry.colorRole.join(' and ')}; explicit materials roles win.`, samples: [{ color: '#aa5533' }] });
  const role = entry.roles.find(use => !use.when)?.role ?? entry.roles[0].role;
  result.push({ field: 'materials', type: 'MaterialOverrides', default: 'inherit', update: 'rebuild', description: 'Partial instance roles over the scene palette; only declared roles affect this model. Fixed decoration keeps its definition tones.', samples: [{ materials: { [role]: '#123456' } }] });
  if (entry.variants) result.push({ field: asset === 'building' ? 'building.type' : 'variant', type: entry.variants.map(value => `'${value}'`).join(' | '), default: entry.variants[0], update: 'rebuild', description: asset === 'building' ? 'Exterior style; building.type selects the geometry, not AssetNode.variant.' : 'Selects the documented silhouette or static configuration; see the model notes.', samples: entry.variants.map(variant => asset === 'building' ? { building: { type: variant as NonNullable<NodeSample['building']>['type'] } } : { variant }) });
  const count = assetCountDefinitions[asset];
  if (count) {
    const values = count.kind === 'range' ? [count.min, count.max] : count.values;
    result.push({ field: 'count', type: count.kind === 'range' ? `integer ${count.min}–${count.max}, step ${count.step}` : `exactly ${count.values.join(', ')}`, default: String(count.default), update: 'rebuild', description: `${count.label}, in ${count.unit}. Every visible part shares the owning node identity; counts do not invent source records.`, samples: values.map(count => ({ count })) });
    result.push({ field: 'multiplier', type: 'positive integer', default: 'none', update: 'rebuild', description: 'Disclosed units per visible part; changes symbolic meaning rather than geometric scale. The host preserves authoritative totals.', samples: [{ count: count.default, multiplier: 10 }] });
  }
  if (assetCountLayoutDefaults[asset]) result.push({ field: 'countLayout', type: "'compact' | 'reserved'", default: assetCountLayoutDefaults[asset], update: 'rebuild', description: 'Compact occupancy or reserved maximum slots.', samples: [{ countLayout: 'reserved' }] });
  const footprint = assetFootprintDefinitions[asset];
  if (footprint) result.push({ field: 'footprint', type: '[width, depth] in metres', default: JSON.stringify(footprint.default), update: 'rebuild', description: `Local x/z dimensions in [${footprint.min.join(', ')}]–[${footprint.max.join(', ')}]. Variant-specific defaults are declared in assetFootprintDefinitions; invalid sizes are rejected.`, samples: [{ footprint: footprint.min }, { footprint: footprint.max }] });
  const measurement = assetMeasurementDefinitions[asset];
  if (measurement) result.push({ field: 'measurement', type: 'Measurement', default: JSON.stringify(measurement.default), update: 'rebuild', description: 'Decimal value or null, explicit min/max, unit, target and ordered threshold bands. Out-of-range labels stay exact; fill is bounded. Measured mode rejects count and multiplier inputs.', samples: [{ measurement: { value: null } }, { measurement: { value: 0 } }, { measurement: { value: 110, target: 80, bands: [{ from: 0, to: 100, state: 'normal' }] } }] });
  const display = assetDisplayDefinitions[asset];
  if (display) result.push({ field: 'display', type: 'DisplayReading', default: JSON.stringify(display.default), update: 'rebuild', description: 'Host-supplied number or integer seconds. Running readings use relative scene time; updates restart from the supplied value. No scheduling or authoritative time source.', samples: display.default.kind === 'number' ? [{ display: { kind: 'number', value: null } }, { display: { kind: 'number', value: -12.34, decimals: 2 } }] : [{ display: { ...display.default, seconds: 0, running: true } }] });
  if (assetLabelSurfaces[asset]) result.push({ field: 'surfaceLabel', type: 'SurfaceLabel', default: 'none', update: 'rebuild', description: 'Bounded text or self-contained SVG on the surfaces in assetLabelSurfaces. Artwork owns its texture/decoder lifecycle and does not change record identity.' });
  if (asset === 'building') result.push({ field: 'building', type: 'BuildingOptions', default: '{ size: [8, 3.6, 6], view: closed, cutaway: low-walls, peekOnHover: false }', update: 'rebuild', description: 'Metric [width, height, depth], each 2–100 m; closed/peek/open cutaway, optional hover peek and wall/roof/floor/trim colors. Explicit building.colors overrides semantic roles. Interior records and loading belong to the host.', samples: [{ building: { view: 'open' } }, { building: { view: 'peek', cutaway: 'front', peekOnHover: true } }, { building: { size: [12, 5, 9], type: 'office' } }, { building: { colors: { wall: '#123456' } } }] });
  if (asset === 'shopping-cart') result.push({ field: 'contents', type: 'ContainerContents', default: 'none', update: 'rebuild', description: 'Source-backed content lines; bounded proxies do not invent unit identities.', samples: [{ contents: { lines: [{ id: 'item', title: 'Item', quantity: 2 }] } }] });
  if (['heated-pass', 'espresso-machine', 'pizza-oven'].includes(asset)) result.push({ field: 'heatEnabled', type: 'boolean', default: 'true', update: 'rebuild', description: 'Visible heat glow, steam or fire independently of host State. Scene motion gates still control animation.', samples: [{ heatEnabled: false }, { heatEnabled: true }] });
  if (assetVisualStates[asset]) result.push({ field: 'state', type: 'VisualState', default: 'normal', update: 'rebuild', description: 'Native host status with the visual mapping declared below; unsupported values use the normal appearance.', samples: STATES.map(state => ({ state })) });
  if (entry.animation === 'local') result.push({ field: 'localMotion', type: 'boolean', default: 'true', update: 'rebuild', description: 'The renderer skips local animation when false. A true value cannot override scene motion, pause or reduced-motion gates.', samples: [{ localMotion: false }] });
  result.push({ field: 'position / rotation / scale', type: 'Vec3; rotations in radians', default: 'position [0,0,0], rotation [0,0,0], scale [1,1,1]', update: 'transform', description: 'Host placement around the documented model origin. Scale changes geometric size, never quantity.' });
  return result;
}

function describe(entry: CatalogEntry): ObjectDescriptor {
  return Object.freeze({
    asset: entry.asset, name: entry.name, category: entry.category, purpose: entry.purpose, version: 1,
    geometry: { units: 'metres', pivot: entry.pivot, forward: '+z', up: '+y', bounds: entry.bounds, ...(entry.largest ? { largest: entry.largest } : {}), note: entry.placement },
    palette: { roles: entry.roles, ...(entry.colorRole ? { colorRole: entry.colorRole } : {}), fixed: entry.fixed },
    customization: options(entry),
    states: assetVisualStates[entry.asset] ? { shown: assetVisualStates[entry.asset], unchanged: STATES.filter(state => !assetVisualStates[entry.asset].includes(state)), parts: 'Only native status parts respond to the supported host states; see palette roles and model notes.', alternative: 'Use the node label or host HTML record view for status text. Selection and hover use a separate renderer ring.' } : neutralModelStates(entry.name),
    motion: { animation: entry.animation, staticPose: entry.animation === 'local' ? 'The built pose remains useful when motion is off; local animation changes only descendants.' : 'Always static; any moving placement is host-driven.', transform: TRANSFORM, policy: 'The shared scene clock owns animation time. Scene motion-off, pause and reduced motion win over instance options; disposal removes the animator.' },
    interaction: { selectable: 'Selectable when the node has entityId or selectable: true; all subparts share that node.', hit: 'Visible raycastable meshes; decorative linework and flat markings may opt out.', anchors: entry.anchors, slots: entry.slots, relationships: entry.notes },
    lifecycle: { ownership: 'instance', textures: assetLabelSurfaces[entry.asset] ? 'Optional surface-label textures and decoding callbacks belong to the instance.' : 'None.', animator: entry.animation === 'local', update: 'Configuration and palette changes rebuild the model; transforms update the existing root. The renderer retains node and selection identity.', disposal: 'disposeObject releases geometry, mesh/line materials, label textures and the root animator. No model owns a timer or subscription.' },
    evidence: { examples: [`/docs/objects/${entry.asset}`, entry.example], tests: ['tests/object-contract.test.ts', 'tests/catalog-descriptors.test.ts'], limits: [entry.notes, 'Catalog pages provide JS/React/Vue snippets and one shared-renderer live preview; snippets are not separate standalone projects. No hardware FPS budget is asserted.'] },
  } satisfies ObjectDescriptor);
}

