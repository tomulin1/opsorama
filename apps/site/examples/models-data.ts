import { createSceneStore, type AssetNode, type GroundNode, type SceneDefinition, type SceneNode, type SceneSettings, type SceneStore, type Selection, type Vec3, type ZoneNode } from '@opsorama/core';
import { createAssetRegistry, type AssetRegistry, type SceneRenderer } from '@opsorama/three';
import { gltfAsset } from '@opsorama/three/gltf';
import { furnitureKit } from '@opsorama/objects/furniture';
import { workItemsKit } from '@opsorama/objects/work-items';

/*
 * The glTF models example: delivery drones loaded from a GLB file next to catalog models. Parked drones stand on a pad,
 * two drones fly loops with spinning rotors; every drone shares the file's geometry, materials and texture, and the
 * renderer draws their repeated parts as instanced batches.
 */

/** The example model: an original Opsorama drone (MIT), generated by scripts/build-example-models.mjs. */
export const DRONE_URL = '/models/drone.glb';

/**
 * Catalog kits plus two glTF assets from the same file: parked drones stand still, flying drones play the file's
 * "rotors" clip. The file loads once; both factories share it.
 */
export const modelAssets: AssetRegistry = createAssetRegistry(furnitureKit, workItemsKit, {
  drone: gltfAsset(DRONE_URL, { height: .7 }),
  'drone-flying': gltfAsset(DRONE_URL, { height: .7, animation: 'rotors' }),
});

export const floor: GroundNode = { id: 'floor', kind: 'ground', size: [14, 9], color: '#e6edf5' };
export const pad: ZoneNode = { id: 'drone-pad', kind: 'zone', size: [5.4, 3.4], position: [1.6, 0, .6], label: 'Drone pad' };
export const catalogNodes: readonly AssetNode[] = [
  { id: 'rack-a', kind: 'asset', asset: 'pallet-rack', position: [-4.6, 0, -1.6], label: 'Rack A' },
  { id: 'rack-b', kind: 'asset', asset: 'pallet-rack', position: [-4.6, 0, 1.6] },
  { id: 'outbound', kind: 'asset', asset: 'parcel-base', position: [-1.8, 0, 2.6], count: 9, label: 'Outbound' },
];

/** Parked drones on the pad, in rows of four; each is a record the host can select. */
export const parkedDrones = (count: number): AssetNode[] => Array.from({ length: count }, (_, index) => ({
  id: `drone-${index + 1}`, kind: 'asset', asset: 'drone', entityId: `drone:${index + 1}`, label: index === 0 ? 'Drone 1' : undefined,
  position: [-.4 + (index % 4) * 1.3, 0, -.4 + Math.floor(index / 4) * .9], rotation: [0, Math.PI, 0],
}));

const loop = (center: Vec3, radius: number, height: number): Vec3[] => Array.from({ length: 9 }, (_, index) => { const angle = index / 8 * Math.PI * 2; return [center[0] + Math.cos(angle) * radius, height, center[2] + Math.sin(angle) * radius]; });
/** Two drones flying loops over the scene, with the "rotors" clip playing while scene motion is on. */
export const flyingDrones: readonly AssetNode[] = [
  { id: 'flyer-1', kind: 'asset', asset: 'drone-flying', entityId: 'drone:flyer-1', label: 'Flight 1', position: [4.6, 2.2, -1.5], route: { points: loop([1.6, 0, -.6], 3.2, 2.2), speed: 1.6, loop: true } },
  { id: 'flyer-2', kind: 'asset', asset: 'drone-flying', entityId: 'drone:flyer-2', position: [-1.2, 1.6, .6], route: { points: loop([-1.2, 0, .6], 1.8, 1.6), speed: 1.2, loop: true } },
];

export const modelsDefinition = (count: number): SceneDefinition => ({ schemaVersion: 1, nodes: [floor, pad, ...catalogNodes, ...parkedDrones(count), ...flyingDrones] });
export const makeModelsStore = (definition: SceneDefinition, settings: Partial<SceneSettings> = {}): SceneStore => createSceneStore(definition, settings);
export const selectionSummary = (selection: Selection | null) => selection ? `Selected: ${selection.nodeId}${selection.entityId ? ` (${selection.entityId})` : ''}` : 'Selected: nothing';

/** What the example page changes: the number of parked drones and the theme. */
export interface ModelsData { count: number; theme: SceneSettings['theme'] }
/** A mounted example; `setData` changes the scene without remounting. */
export interface ModelsSession { store: SceneStore; setData(data: ModelsData): void; dispose(): void }
export interface ModelsCallbacks { ready(renderer: SceneRenderer): void; select(selection: Selection | null): void; error(error: Error): void }
/** Every node of the scene for a drone count, for the adapters that render components. */
export const sceneNodes = (count: number): SceneNode[] => modelsDefinition(count).nodes.slice();

/** The usage snippet of each adapter. */
export function modelsSnippet(framework: 'react' | 'vue' | 'javascript'): string {
  const registry = `import { createAssetRegistry } from '@opsorama/three';
import { gltfAsset } from '@opsorama/three/gltf';
import { furnitureKit } from '@opsorama/objects/furniture';

// The file loads once; every drone shares its geometry, materials and textures.
const assets = createAssetRegistry(furnitureKit, {
  drone: gltfAsset('/models/drone.glb', { height: 0.7 }),
  'drone-flying': gltfAsset('/models/drone.glb', { height: 0.7, animation: 'rotors' }),
});`;
  if (framework === 'javascript') return `${registry}

const store = createSceneStore({ schemaVersion: 1, nodes: [
  { id: 'rack-a', kind: 'asset', asset: 'pallet-rack', position: [-4.6, 0, -1.6] },
  { id: 'drone-1', kind: 'asset', asset: 'drone', entityId: 'drone:1', position: [-0.4, 0, -0.4] },
  { id: 'flyer-1', kind: 'asset', asset: 'drone-flying', route: { points: loop, speed: 1.6, loop: true } },
] });
// Each drone shows a placeholder box until the file has loaded; a file that fails to load is reported here.
const renderer = createSceneRenderer(container, store, { assets, onError: error => console.warn(error.message) });`;
  if (framework === 'react') return `${registry}

<DashboardProvider store={store}>
  <SceneCanvas assets={assets} onSelect={setSelection} onError={error => console.warn(error.message)} />
  <Asset id="rack-a" asset="pallet-rack" position={[-4.6, 0, -1.6]} />
  {drones.map(drone => <Asset key={drone.id} {...drone} asset="drone" />)}
  <Asset id="flyer-1" asset="drone-flying" route={{ points: loop, speed: 1.6, loop: true }} />
</DashboardProvider>`;
  return `${registry}

h(DashboardProvider, { store }, () => [
  h(SceneCanvas, { assets, onSelect, onError: error => console.warn(error.message) }),
  h(Asset, { id: 'rack-a', asset: 'pallet-rack', position: [-4.6, 0, -1.6] }),
  ...drones.value.map(drone => h(Asset, { key: drone.id, ...drone, asset: 'drone' })),
  h(Asset, { id: 'flyer-1', asset: 'drone-flying', route: { points: loop, speed: 1.6, loop: true } }),
])`;
}
